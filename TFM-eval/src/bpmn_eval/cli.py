"""CLI entrypoint for bpmn-eval."""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

from bpmn_eval.comparison import aggregate_results
from bpmn_eval.pipeline import evaluate_all
from bpmn_eval.reporting.csv_reporter import write_csv_report
from bpmn_eval.reporting.json_reporter import write_json_report
from bpmn_eval.reporting.summary import print_summary


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        prog="bpmn-eval",
        description=(
            "Evaluate BPMN diagrams generated by LLMs — "
            "compare zero-shot XML vs DSL-intermediated approaches."
        ),
    )
    parser.add_argument(
        "data_dir",
        type=Path,
        help="Path to data/ directory containing cases/ subdirectory",
    )
    parser.add_argument(
        "-o", "--output",
        type=Path,
        default=Path("results"),
        help="Output directory for reports (default: results/)",
    )
    parser.add_argument(
        "--format",
        choices=["json", "csv", "both"],
        default="both",
        help="Output format (default: both)",
    )
    parser.add_argument(
        "--schema-dir",
        type=Path,
        default=Path("schemas"),
        help="Path to directory containing BPMN20.xsd (default: schemas/)",
    )
    parser.add_argument(
        "-v", "--verbose",
        action="store_true",
        help="Enable verbose logging",
    )

    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(levelname)s: %(message)s",
    )

    schema_path = str(args.schema_dir / "BPMN20.xsd")

    try:
        cases = evaluate_all(args.data_dir, schema_path=schema_path)
    except FileNotFoundError as exc:
        logging.error("%s", exc)
        sys.exit(1)

    if not cases:
        logging.warning("No cases found in %s", args.data_dir / "cases")
        sys.exit(0)

    aggregates = aggregate_results(cases)

    # Always print summary to stdout
    print_summary(cases, aggregates)

    # Write reports
    output_dir = args.output
    fmt = args.format

    if fmt in ("json", "both"):
        json_path = output_dir / "results.json"
        write_json_report(cases, aggregates, json_path)
        logging.info("JSON report written to %s", json_path)

    if fmt in ("csv", "both"):
        csv_path = output_dir / "results.csv"
        write_csv_report(cases, csv_path)
        logging.info("CSV report written to %s", csv_path)


if __name__ == "__main__":
    main()
